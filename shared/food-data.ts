import type { Cuisine, FoodStatus, FormCategory, Level } from './types';

export interface RawVariant {
  name: string;
  status: FoodStatus;
  fat: Level;
  note: string;
}

export interface RawFood {
  name: string;
  form: FormCategory;
  cuisine: Cuisine;
  status: FoodStatus;
  fat: Level;
  spice: Level;
  aliases: string[];
  tags: string[];
  description: string;
  variants: RawVariant[];
}

interface Opts {
  a?: string[];
  t?: string[];
  d?: string;
  v?: [string, FoodStatus, Level, string][];
  form?: FormCategory;
  cuisine?: Cuisine;
}
type Row = [string, Level, Level, Opts?];

function group(defaults: { status: FoodStatus; form: FormCategory; cuisine: Cuisine; tags?: string[] }, rows: Row[]): RawFood[] {
  return rows.map(([name, fat, spice, o = {}]) => ({
    name,
    form: o.form ?? defaults.form,
    cuisine: o.cuisine ?? defaults.cuisine,
    status: defaults.status,
    fat,
    spice,
    aliases: o.a ?? [],
    tags: [...(defaults.tags ?? []), ...(o.t ?? [])],
    description: o.d ?? '',
    variants: (o.v ?? []).map(([vn, status, vf, note]) => ({ name: vn, status, fat: vf, note })),
  }));
}

